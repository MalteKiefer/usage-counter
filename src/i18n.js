export const DICTIONARIES = { de: DE, en: EN };

// Returns t(key, vars). Missing keys fall back to German, then to the key itself.
export function translator(lang) {
  const dict = DICTIONARIES[lang] ?? DE;
  return (key, vars = {}) => {
    const template = dict[key] ?? DE[key] ?? key;
    return template.replace(/\{(\w+)\}/g, (match, name) => (name in vars ? String(vars[name]) : match));
  };
}

export const I18nContext = createContext(translator('de'));
export const useT = () => useContext(I18nContext);
